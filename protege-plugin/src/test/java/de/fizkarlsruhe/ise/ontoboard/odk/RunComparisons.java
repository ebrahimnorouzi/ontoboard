package de.fizkarlsruhe.ise.ontoboard.odk;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import org.semanticweb.owlapi.apibinding.OWLManager;
import org.semanticweb.owlapi.io.FileDocumentSource;
import org.semanticweb.owlapi.model.IRI;
import org.semanticweb.owlapi.model.MissingImportHandlingStrategy;
import org.semanticweb.owlapi.model.OWLAnnotation;
import org.semanticweb.owlapi.model.OWLImportsDeclaration;
import org.semanticweb.owlapi.model.OWLOntology;
import org.semanticweb.owlapi.model.OWLOntologyManager;
import org.semanticweb.owlapi.model.parameters.Imports;
import org.semanticweb.owlapi.util.VersionInfo;
import org.semanticweb.owlapi.vocab.OWLRDFVocabulary;

/**
 * How what an ODK target did is held against what ODK's own make did: the lines make said, what
 * ROBOT said of its checks and in its report, the files the run made, the tables by their rows,
 * the ontologies by what they say. {@code FallbackEquivalenceTest} holds OntoBoard's engine
 * against ODK's recorded runs with these; {@code SideBySideLiveTest} holds it against ODK's make
 * running now. Moved here from the first so that both say "the same" in one way.
 */
final class RunComparisons {

    /** The age ODK's recording gave every file of the project: 2026-11-11 12:00 UTC. */
    static final long RECORDED_AGE = 1_794_398_400_000L;

    private RunComparisons() {
    }

    // ------------------------------------------------------------------ the products

    /**
     * ODK's ROBOT writes with OWL API 4.5.29. Protege 5.6.9 has the same one; Protege 5.5.0
     * has 4.5.9, which is also what these tests run on unless told otherwise
     * ({@code -Dowlapi.version=4.5.29}).
     */
    static boolean onOdksOwlApi() {
        return VersionInfo.getVersionInfo().getVersion().startsWith("4.5.29");
    }

    /**
     * A product of the release against ODK's, as closely as the OWL API this runs on allows.
     *
     * <p>The file is ODK's character for character, but for the one line in which the OWL API
     * names its own build - on ODK's own OWL API and, since OntoBoard's engine writes a
     * string as ODK's OWL API writes it ({@code SimpleStrings}), on the older one as well.
     * Only OBO differs there: its header names the Dublin Core properties in full where
     * ODK's declares short names for them.
     */
    static void assertSameProduct(String name, File theirs, File ours) throws Exception {
        if (!onOdksOwlApi() && name.endsWith(".obo")) {
            assertEquals(String.join("\n", withItsShortNamesInFull(lines(read(theirs)))),
                    String.join("\n", lines(read(ours))), name + ": ODK's file, the short names "
                            + "of its header written in full as the older OWL API writes them");
        } else {
            assertSameFile(name, theirs, ours);
        }
    }

    /**
     * A file ROBOT wrote here against the one ODK's ROBOT wrote: character for character,
     * but for what shows the OWL API's version - the line in which it names its build and,
     * on the older one, the default prefix of a file in functional syntax, which that one
     * keeps from the file it read where ODK's takes it from the ontology's new name.
     */
    static void assertSameFile(String name, File theirs, File ours) throws Exception {
        assertEquals(butForWhatShowsTheOwlApi(read(theirs)), butForWhatShowsTheOwlApi(
                read(ours)), name + ": ODK's file, character for character but for what "
                        + "shows the OWL API's version");
    }

    private static String butForWhatShowsTheOwlApi(String text) {
        String generated = butForTheLineOfTheOwlApi(text);
        return onOdksOwlApi() ? generated
                : generated.replaceFirst("(?m)^Prefix\\(:=<[^>]*>\\)$", "Prefix(:=<...>)");
    }

    private static String butForTheLineOfTheOwlApi(String text) {
        return text.replaceAll("<!-- Generated by the OWL API \\(version [^)]*\\) "
                + "https://github.com/owlcs/owlapi -->", "<!-- Generated by the OWL API -->");
    }

    /**
     * An OBO file's lines without its {@code idspace} lines, and with every header property
     * they give a short name to written by its whole IRI.
     */
    private static List<String> withItsShortNamesInFull(List<String> obo) {
        Map<String, String> spaces = new LinkedHashMap<String, String>();
        for (String line : obo) {
            if (line.startsWith("idspace: ")) {
                String[] parts = line.split(" ");
                spaces.put(parts[1] + ":", parts[2]);
            }
        }
        List<String> inFull = new ArrayList<String>();
        for (String line : obo) {
            if (line.startsWith("idspace: ")) {
                continue;
            }
            String written = line;
            for (Map.Entry<String, String> space : spaces.entrySet()) {
                if (line.startsWith("property_value: " + space.getKey())) {
                    written = "property_value: " + space.getValue()
                            + line.substring(("property_value: " + space.getKey()).length());
                }
            }
            inFull.add(written);
        }
        return inFull;
    }

    // ------------------------------------------------------------------ what is compared

    /**
     * The lines of a transcript that are make's own: each recipe line as it says it before it
     * runs it, and its word on entering and leaving the folder, with the folder left out. What
     * the programs print is not among them.
     */
    static List<String> saidByMake(List<String> transcript) {
        List<String> said = new ArrayList<String>();
        for (String line : transcript) {
            if (line.matches("make\\[\\d+\\]: (Entering|Leaving) directory .*")) {
                said.add(line.substring(0, line.indexOf("directory") + "directory".length()));
            } else if (isARecipeLine(line)) {
                said.add(line);
            }
        }
        return said;
    }

    /** A recipe line as make says it before it runs it; not what a program printed. */
    private static boolean isARecipeLine(String line) {
        return line.startsWith("robot ") || line.startsWith("mkdir ")
                || line.startsWith("if [") || line.equals("fi") || line.startsWith("echo ")
                || line.startsWith("make ") || line.startsWith("rsync ")
                || line.startsWith("rm ") || line.startsWith("curl ")
                || line.startsWith("cat ") || line.startsWith("for ")
                || line.equals("done") || line.startsWith("\t");
    }

    /**
     * What ROBOT's report printed: the lines between its own line and make's next. What it
     * says of its rules as it runs them comes sorted here, since ROBOT keeps its rules in a set
     * and runs them in no fixed order; the counts and the findings after them are in theirs.
     */
    static List<String> saidByTheReport(List<String> transcript) {
        List<String> ofItsRules = new ArrayList<String>();
        List<String> after = new ArrayList<String>();
        boolean inside = false;
        for (String line : transcript) {
            if (inside && isARecipeLine(line)) {
                break;
            }
            if (inside) {
                (line.startsWith("WARN: '") ? ofItsRules : after).add(line);
            }
            inside |= line.startsWith("robot ") && line.contains(" report ");
        }
        Collections.sort(ofItsRules);
        ofItsRules.addAll(after);
        return ofItsRules;
    }

    /**
     * The ontology a file holds, by itself: what it imports is named in it and is not
     * fetched, so that a file made part way through a run - the edit file as it is
     * prepared, say, which still imports its modules - can be held against ODK's as well.
     */
    private static OWLOntology byItself(File file) throws Exception {
        OWLOntologyManager reader = OWLManager.createOWLOntologyManager();
        final File nowhere = new File(file.getAbsoluteFile().getParentFile(),
                ".no-such-import");
        reader.getIRIMappers().add(iri -> IRI.create(nowhere));
        reader.setOntologyLoaderConfiguration(reader.getOntologyLoaderConfiguration()
                .setMissingImportHandlingStrategy(MissingImportHandlingStrategy.SILENT));
        return reader.loadOntologyFromOntologyDocument(new FileDocumentSource(file));
    }

    private static Set<String> imported(OWLOntology ontology) {
        Set<String> imports = new TreeSet<String>();
        for (OWLImportsDeclaration declaration : ontology.getImportsDeclarations()) {
            imports.add(declaration.getIRI().toString());
        }
        return imports;
    }

    /**
     * The values of the {@code owl:versionInfo} a file's ontology carries itself, sorted;
     * what it imports is not read.
     */
    static List<String> versionInfos(File file) throws Exception {
        List<String> values = new ArrayList<String>();
        for (OWLAnnotation annotation : byItself(file).getAnnotations()) {
            if (OWLRDFVocabulary.OWL_VERSION_INFO.getIRI().equals(
                    annotation.getProperty().getIRI())
                    && annotation.getValue().asLiteral().isPresent()) {
                values.add(annotation.getValue().asLiteral().get().getLiteral());
            }
        }
        Collections.sort(values);
        return values;
    }

    static List<String> starting(String with, List<String> transcript) {
        List<String> found = new ArrayList<String>();
        for (String line : transcript) {
            if (line.startsWith(with)) {
                found.add(line);
            }
        }
        return found;
    }

    /** A table's header, then its rows sorted: the order of a query's rows is the store's. */
    static List<String> rows(String table) {
        List<String> all = lines(table);
        List<String> rows = new ArrayList<String>(all.subList(1, all.size()));
        Collections.sort(rows);
        rows.add(0, all.get(0));
        return rows;
    }

    static void assertSameOntology(String name, File theirs, File ours) throws Exception {
        OWLOntology recorded = byItself(theirs);
        OWLOntology here = byItself(ours);
        assertEquals(recorded.getOntologyID(), here.getOntologyID(), name + ": its names");
        assertEquals(imported(recorded), imported(here), name + ": what it imports");
        assertEquals(sorted(recorded.getAnnotations()), sorted(here.getAnnotations()),
                name + ": what the ontology says of itself");
        assertEquals(sorted(recorded.getAxioms(Imports.EXCLUDED)),
                sorted(here.getAxioms(Imports.EXCLUDED)), name + ": its axioms");
    }

    private static String sorted(Set<?> things) {
        Set<String> sorted = new TreeSet<String>();
        for (Object thing : things) {
            sorted.add(thing.toString());
        }
        return String.join("\n", sorted);
    }

    // ------------------------------------------------------------------ the disk

    static String read(File file) throws IOException {
        return new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8);
    }

    static List<String> lines(String text) {
        List<String> lines = new ArrayList<String>();
        for (String line : text.replace("\r\n", "\n").split("\n")) {
            lines.add(line);
        }
        return lines;
    }

    /** make decides by the age of files: the recording gave every file of the project one age. */
    static void allOfTheSameAge(File folder) throws IOException {
        try (Stream<Path> all = Files.walk(folder.toPath())) {
            for (Path path : all.collect(Collectors.toList())) {
                path.toFile().setLastModified(RECORDED_AGE);
            }
        }
    }

    static Map<String, String> hashes(File folder) throws Exception {
        Map<String, String> hashes = new TreeMap<String, String>();
        Path root = folder.toPath();
        try (Stream<Path> all = Files.walk(root)) {
            for (Path path : all.collect(Collectors.toList())) {
                if (Files.isRegularFile(path)) {
                    StringBuilder hex = new StringBuilder();
                    for (byte b : MessageDigest.getInstance("SHA-256")
                            .digest(Files.readAllBytes(path))) {
                        hex.append(String.format("%02x", b & 0xff));
                    }
                    hashes.put(root.relativize(path).toString().replace('\\', '/'),
                            hex.toString());
                }
            }
        }
        return hashes;
    }

    /** The files that are new or changed since a look at the folder. */
    static Set<String> madeSince(Map<String, String> before, File folder) throws Exception {
        Set<String> made = new TreeSet<String>();
        for (Map.Entry<String, String> now : hashes(folder).entrySet()) {
            if (!now.getValue().equals(before.get(now.getKey()))) {
                made.add(now.getKey());
            }
        }
        return made;
    }
}
