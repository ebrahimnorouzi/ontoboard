package de.fizkarlsruhe.ise.ontoboard.odk;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.BufferedReader;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import org.junit.jupiter.api.Test;

/**
 * The 1.135.2 project the migration is tested on is there, and is what 1.135.2 made.
 *
 * <p>1.153.0 deletes the code that wrote projects the 1.135.x way, and <em>Update project
 * files...</em> has to carry such a project over to ODK's seed without losing anything of its
 * own. A project made by hand after that code is gone would be what somebody remembers 1.135.2
 * writing, not what it wrote; so one was written by it while it still existed
 * ({@link MigrationFixtureWriter}) and kept, byte for byte, with the files a user adds to one:
 * three classes, an import module, a pattern, a module nothing imports, a question, a relaxed
 * report rule, a release.
 *
 * <p>Read from the source folder, not the class path, as the goldens are: Maven's resource copying
 * leaves {@code .gitignore} and {@code .gitattributes} out, and the project has both.
 */
class MigrationFixtureTest {

    /** {@code src/test/resources/<path>} of this module. */
    static File fixture(String path) {
        File module = new File(System.getProperty("basedir", System.getProperty("user.dir")));
        return new File(module, "src/test/resources/" + path);
    }

    private static String firstLine(File file) {
        try (BufferedReader reader = Files.newBufferedReader(file.toPath(),
                StandardCharsets.UTF_8)) {
            return reader.readLine();
        } catch (IOException missing) {
            throw new AssertionError("Could not read " + file.getAbsolutePath() + ": "
                    + missing.getMessage(), missing);
        }
    }

    @Test
    void theFixtureIsA1352Project() {
        File root = fixture("odk/migration/eggboil-1.135.2");
        assertEquals("# WARNING: generated by OntoBoard. Do NOT edit by hand.",
                firstLine(new File(root, "src/ontology/Makefile")));
        for (String path : new String[] {"src/ontology/eggboil-edit.owl",
                "src/ontology/eggboil-odk.yaml", "src/ontology/profile.txt",
                "src/ontology/catalog-v001.xml", "src/ontology/imports/mini_import.owl",
                "src/ontology/imports/mini_terms.txt",
                "src/ontology/imports/measurement_import.owl",
                "src/ontology/imports/measurement_terms.txt",
                "src/ontology/imports/unused_import.owl", "src/ontology/imports/unused_terms.txt",
                "src/ontology/upstream/mini.owl", "src/sparql/check_labels.rq",
                "src/sparql/every_dataset_has_part.rq", "releases/1.0.0/eggboil.owl",
                "eggboil.owl", "docs/index.md", "mkdocs.yaml", ".gitattributes", ".gitignore",
                "README.md"}) {
            assertTrue(new File(root, path).isFile(), path);
        }
    }
}
