"""Derives a worked example from each pattern's own axioms.

Asked for: "for each pattern I need an example.ttl that used the pattern and this example should
be shown with ontoink that users can see how patterns are used".

WHY DERIVED RATHER THAN WRITTEN. There are 164 patterns. An example has to instantiate the
pattern's classes and connect them with its properties the right way round, and the pattern
itself already says which way round that is: an object property's rdfs:domain is the type its
subject must have and its rdfs:range is the type its object must have. Reading that out of the
file cannot get a direction backwards, which is the single most common error in a hand-written
example. So the structure is derived, and only the names are a matter of taste.

WHAT IT WILL NOT DO. It does not invent an axiom the pattern does not have. A pattern whose
properties declare no domain or range gives a graph with nothing to connect, and this reports it
rather than guessing: the honest outcome is a list of patterns a person has to write an example
for, not 164 files of which some are quietly wrong. It also never overwrites an example that
somebody has already curated unless asked - see --force.

WHAT MAKES AN EXAMPLE GOOD, WHICH THIS ONLY PARTLY ACHIEVES. The individuals here are named
after their classes - "a Sample", "a Measurement" - which shows the shape and teaches nothing
about the domain. For the patterns that matter most, somebody replaces those with real ones: a
real sample, a real instrument, a real measurement. This generator's job is to make all 164
structurally correct and leave a marker saying which are still generic.

Usage, from the repository root:

    python -I tools/make-pattern-examples.py            # write what is missing, report the rest
    python -I tools/make-pattern-examples.py --force    # rewrite even curated examples
    python -I tools/make-pattern-examples.py --only mwo-sample-measurement
    python -I tools/make-pattern-examples.py --check    # write nothing; exit 1 if any are missing

Needs rdflib.
"""
import argparse
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PATTERNS = os.path.join(ROOT, "patterns")

# The marker that says an example is as the generator left it. A curator who improves an example
# deletes this line, and then --force is the only thing that will touch it.
GENERATED = "# GENERATED by tools/make-pattern-examples.py - replace the generic names with real"

BUILT_IN = (
    "http://www.w3.org/1999/02/22-rdf-syntax-ns#",
    "http://www.w3.org/2000/01/rdf-schema#",
    "http://www.w3.org/2002/07/owl#",
    "http://www.w3.org/2001/XMLSchema#",
    "http://www.w3.org/2004/02/skos/core#",
    "http://purl.org/dc/elements/1.1/",
    "http://purl.org/dc/terms/",
    "http://www.ontologydesignpatterns.org/schemas/cpannotationschema.owl#",
)


def local(iri):
    said = str(iri)
    cut = max(said.rfind("#"), said.rfind("/"))
    return said[cut + 1:] if cut >= 0 else said


def safe_name(name):
    """A local name Turtle will accept after a prefix."""
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", name).strip("_-")
    if not cleaned or not re.match(r"[A-Za-z_]", cleaned):
        cleaned = "x" + (cleaned or "term")
    return cleaned


# A value of the right datatype. Writing "a value" for every one of them, which is what the
# first version did, made bag:size - declared xsd:integer - carry a string, so the example
# asserted something the pattern forbids.
SAMPLE = {
    "integer": '1', "int": '1', "long": '1', "nonNegativeInteger": '1', "positiveInteger": '1',
    "decimal": '1.5', "double": '1.5', "float": '1.5',
    "boolean": 'true',
    # xsd:date is NOT in the OWL 2 datatype map, so HermiT refuses an ontology that uses one -
    # reported from a ROBOT/HermiT run over a generated temporal example. A plain string is
    # weaker than a typed literal and it is the only thing that both parses and reasons.
    # xsd:dateTime IS in the map, so that one stays typed.
    "date": '"2026-01-01"',
    "dateTime": '"2026-01-01T00:00:00"^^xsd:dateTime',
    "anyURI": '"https://example.org/"^^xsd:anyURI',
}


def literal_for(datatype):
    if datatype is None:
        return '"a value"'
    return SAMPLE.get(local(datatype), '"a value"')


def readable(name):
    """`SocialAgent` -> `a Social Agent`; `MWO_0001022` -> `a MWO_0001022`."""
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name).replace("_", " ").strip()
    article = "an" if spaced[:1].upper() in "AEIOU" else "a"
    return article + " " + spaced


def is_built_in(iri):
    return any(str(iri).startswith(prefix) for prefix in BUILT_IN)


def local_library():
    """Every pattern's ontology IRI, mapped to its file, so owl:imports can be followed.

    TWENTY-TWO OF THESE PATTERNS SAY NOTHING ON THEIR OWN. agentrole declares three classes and
    imports objectrole, which is where isRoleOf actually lives; without following that import the
    pattern looks like three unconnected classes and the example came out as three unconnected
    individuals. The imports are nearly all other patterns in this same library, so they can be
    followed without a network.
    """
    import rdflib
    from rdflib import OWL, RDF

    index = {}
    for pattern_id in sorted(os.listdir(PATTERNS)):
        path = os.path.join(PATTERNS, pattern_id, "pattern.ttl")
        if not os.path.isfile(path):
            continue
        try:
            graph = rdflib.Graph()
            graph.parse(path, format="turtle")
        except Exception:                            # noqa: BLE001 - a broken file is reported
            continue                                 #                 by the caller, not here
        for iri in graph.subjects(RDF.type, OWL.Ontology):
            index[str(iri)] = path
            # ODP imports are written with and without the .owl suffix in different files.
            index[str(iri).rstrip("#")] = path
    return index


def shape_of(path, library=None, depth=2):
    """What a pattern says can be asserted: its classes, and its properties' domains and ranges.

    Only named classes in a non-built-in namespace count. A restriction's filler, a blank node
    and an annotation property are all deliberately ignored: an example is individuals and the
    edges between them, and an annotation property is not modelling.
    """
    import rdflib
    from rdflib import OWL, RDF, RDFS
    from rdflib.collection import Collection

    graph = rdflib.Graph()
    graph.parse(path, format="turtle")

    # The pattern's own terms, before any import, so that an example never prefers an imported
    # class where the pattern has one of its own.
    own = set(graph.subjects(RDF.type, OWL.Class))

    if library and depth > 0:
        seen = {path}
        todo = [(graph, depth)]
        while todo:
            here, left = todo.pop()
            if left <= 0:
                continue
            for imported in list(here.objects(None, OWL.imports)):
                where = library.get(str(imported)) or library.get(str(imported).rstrip("#"))
                if not where or where in seen:
                    continue
                seen.add(where)
                try:
                    added = rdflib.Graph()
                    added.parse(where, format="turtle")
                except Exception:                    # noqa: BLE001
                    continue
                graph += added
                todo.append((added, left - 1))

    classes = set()
    for subject in graph.subjects(RDF.type, OWL.Class):
        if isinstance(subject, rdflib.URIRef) and not is_built_in(subject):
            classes.add(subject)

    def typed(subject, predicate):
        """The first named value, for naming and connecting."""
        for value in graph.objects(subject, predicate):
            if isinstance(value, rdflib.URIRef) and not is_built_in(value):
                return value
        return None

    def all_typed(subject, predicate):
        """EVERY named value, because two domain axioms on one property mean the intersection.

        spatial-graph-adapter-sga declares hasType with domain Attribute AND domain
        ContextualizedRelation. Taking only the first one typed the individual as an Attribute
        and left the example asserting something the pattern forbids - caught by the checker,
        which requires every domain axiom to hold.
        """
        return [v for v in graph.objects(subject, predicate)
                if isinstance(v, rdflib.URIRef) and not is_built_in(v)]

    # WHICH CLASSES THE PATTERN SAYS NOTHING CAN BE IN BOTH OF. Needed because several domain
    # axioms on one property are a conjunction, and a conjunction of disjoint classes is empty:
    # see the guard in example_for. Both spellings are read - owl:disjointWith for a pair, and
    # owl:AllDisjointClasses with an owl:members list for a group, which is what
    # spatial-graph-adapter-sga uses.
    disjoint = set()
    for one, _, other in graph.triples((None, OWL.disjointWith, None)):
        if isinstance(one, rdflib.URIRef) and isinstance(other, rdflib.URIRef):
            disjoint.add(frozenset((one, other)))
    for axiom in graph.subjects(RDF.type, OWL.AllDisjointClasses):
        for members in graph.objects(axiom, OWL.members):
            try:
                named = [m for m in Collection(graph, members)
                         if isinstance(m, rdflib.URIRef)]
            except Exception:                        # noqa: BLE001 - a malformed list says nothing
                continue
            for first in range(len(named)):
                for second in range(first + 1, len(named)):
                    disjoint.add(frozenset((named[first], named[second])))

    inverses = set()
    for one, _, other in graph.triples((None, OWL.inverseOf, None)):
        # Only the second of a pair is dropped, so one direction is always asserted.
        if one not in inverses:
            inverses.add(other)

    links = []
    for prop in graph.subjects(RDF.type, OWL.ObjectProperty):
        if not isinstance(prop, rdflib.URIRef) or is_built_in(prop) or prop in inverses:
            continue
        links.append({
            "property": prop,
            "domain": typed(prop, RDFS.domain),
            "range": typed(prop, RDFS.range),
            "domains": all_typed(prop, RDFS.domain),
            "ranges": all_typed(prop, RDFS.range),
            "inverse": typed(prop, OWL.inverseOf),
        })

    data = []
    for prop in graph.subjects(RDF.type, OWL.DatatypeProperty):
        if not isinstance(prop, rdflib.URIRef) or is_built_in(prop):
            continue
        data.append({"property": prop, "domain": typed(prop, RDFS.domain),
                     "range": typed(prop, RDFS.range)})

    # A leaf is a class nothing else in the pattern specialises: the most specific thing to make
    # an individual of. A pattern whose classes are all intermediate still gets them all.
    parents = set()
    for _, _, parent in graph.triples((None, RDFS.subClassOf, None)):
        if isinstance(parent, rdflib.URIRef):
            parents.add(parent)
    mine = sorted(c for c in classes if c in own) or sorted(classes)
    leaves = [c for c in mine if c not in parents] or mine

    said = {}
    for cls in classes:
        for value in graph.objects(cls, RDFS.label):
            said[cls] = str(value)
            break

    return {"classes": sorted(classes), "links": links, "data": data, "leaves": leaves,
            "labels": said, "namespaces": dict(graph.namespaces()), "disjoint": disjoint}


def untyped_example(pattern_id, shape, links):
    """An example for a pattern that is only properties.

    One whole, and one part per property, so a pattern like winstonpartwhole - eight different
    kinds of part-of - shows all eight kinds against the same whole instead of eight unrelated
    pairs. The individuals carry no type beyond owl:NamedIndividual, because the pattern does
    not say what type they should have.
    """
    base = None
    for link in links:
        iri = str(link["property"])
        cut = max(iri.rfind("#"), iri.rfind("/"))
        base = iri[:cut + 1]
        break
    short = None
    for prefix, namespace in shape["namespaces"].items():
        if str(namespace) == base and prefix:
            short = prefix
            break
    if not short:
        stem = (base or "").rstrip("#/").rsplit("/", 1)[-1]
        short = re.sub(r"[^A-Za-z0-9]+", "", re.sub(r"\.(owl|ttl|rdf)$", "", stem)).lower() or "p"

    lines = [GENERATED,
             "# names, and delete this line and the next so that --force is needed to lose",
             "# your work. This pattern declares properties and no classes, so the individuals",
             "# below are untyped - which is what the pattern says about them.",
             "",
             "@prefix %s: <%s> ." % (short, base),
             "@prefix ex: <https://w3id.org/ontoboard/example/%s#> ." % pattern_id,
             "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
             "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
             "",
             "ex:Whole a owl:NamedIndividual ;",
             '    rdfs:label "the whole" ;']
    ordered = sorted(links, key=lambda l: str(l["property"]))
    parts = []
    taken = set()
    for at, link in enumerate(ordered):
        name = local(link["property"])
        # `hasPart` is a relation; the thing at the other end of it is a `Part`. Stripping the
        # relation words is what turns ex:HasPartPart - which the first version produced - into
        # ex:Part, and "the has part part" into "the part".
        bare = re.sub(r"^(has|is|po)[-_]?", "", name, flags=re.I)
        bare = re.sub(r"[-_]?of$", "", bare, flags=re.I)
        # `spatially-located-in` has to become SpatiallyLocatedIn and "spatially located in",
        # not Spatiallylocatedin and "the spatiallylocatedin". Split on the separators first.
        words = [w for w in re.split(r"[^A-Za-z0-9]+", bare) if w]
        bare = "".join(w[0].upper() + w[1:] for w in words) or ("Related%d" % at)
        unique = bare
        suffix = 2
        while unique in taken:
            unique = bare + str(suffix)
            suffix += 1
        taken.add(unique)
        parts.append((link, name, unique, re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", bare).lower()))

    for at, (_, name, individual, _label) in enumerate(parts):
        last = at == len(parts) - 1
        lines.append("    %s:%s ex:%s%s" % (short, name, individual, " ." if last else " ;"))
    lines.append("")
    for _link, _name, individual, label in parts:
        lines.append("ex:%s a owl:NamedIndividual ;" % individual)
        lines.append('    rdfs:label "the %s" .' % label)
        lines.append("")
    return "\n".join(lines)


def example_for(pattern_id, shape):
    """The Turtle, or None with a reason when the pattern does not say enough to build one."""
    # Only links whose ends the pattern actually declares. A domain or range naming a class
    # that is neither declared nor imported is a defect in the pattern - affordance points at
    # Task, notepattern at Voice, policy at Agent - and an example that instantiated it would
    # assert a type nothing defines and make the pattern look sound.
    links = [l for l in shape["links"]
             if l["domain"] in shape["classes"] and l["range"] in shape["classes"]]

    # A PROPERTY WHOSE DOMAINS ARE DISJOINT HAS AN EMPTY DOMAIN, so no individual can be in it
    # and no example can exercise it.
    #
    # MEASURED: spatial-graph-adapter-sga declares hasAttribute with rdfs:domain Attribute AND
    # rdfs:domain ContextualizedRelation, and then declares those two classes disjoint in an
    # owl:AllDisjointClasses axiom. Several domain axioms are a conjunction, so the domain is
    # Attribute AND ContextualizedRelation, which is empty - HermiT reports both classes
    # unsatisfiable. Asserting the individual into both, which is what every domain axiom
    # holding means, produced an example HermiT then called INCONSISTENT. The pattern, as its
    # authors published it, cannot have an instance here; the only honest output is to leave the
    # property out and say why.
    def disjoint_pair(group):
        named = [c for c in (group or []) if c is not None]
        for first in range(len(named)):
            for second in range(first + 1, len(named)):
                if frozenset((named[first], named[second])) in shape.get("disjoint", set()):
                    return (named[first], named[second])
        return None

    empty_domains = []
    usable = []
    for link in links:
        clash = disjoint_pair(link.get("domains")) or disjoint_pair(link.get("ranges"))
        if clash:
            empty_domains.append((link["property"], clash))
        else:
            usable.append(link)
    links = usable

    # Refused outright rather than worked around. Once a property's domain is empty, the classes
    # that must take part in it are unsatisfiable too - Attribute must be the object of a
    # hasAttribute edge that can have no subject - and an individual of an unsatisfiable class
    # makes the whole example inconsistent however few types it is given. Writing a smaller
    # example here would hide a broken pattern behind a graph that looks fine.
    if empty_domains:
        return None, ("it declares disjoint domains for "
                      + ", ".join(sorted(local(prop) + " (" + local(one) + " and " + local(other)
                                         + " are disjoint)"
                                         for prop, (one, other) in empty_domains))
                      + ", so that property's domain is empty and no individual can instantiate "
                        "it")

    # A PATTERN CAN BE NOTHING BUT PROPERTIES, and three of these are: partof and constituency
    # declare hasPart/isPartOf over owl:Thing, and winstonpartwhole declares eight part-of
    # relations with no domain or range at all. There is no class to instantiate, which is why
    # the first version of this refused all three - but the pattern is still about the edge, and
    # two untyped individuals joined by it is exactly the example a reader wants. owl:Thing is
    # deliberately not written as a type: everything is an owl:Thing, so asserting it says
    # nothing and adds a node to every graph.
    if not links and not shape["classes"] and shape["links"]:
        anonymous = []
        for link in shape["links"]:
            anonymous.append({"property": link["property"], "domain": None, "range": None,
                              "inverse": link["inverse"]})
        return untyped_example(pattern_id, shape, anonymous), None

    if not links and not shape["classes"]:
        return None, "it declares no classes and no object properties, so there is nothing an "\
                     "example could assert"
    if not links and not shape["leaves"]:
        return None, "it declares no classes that could be instantiated"

    # One individual per class, reused across every property that mentions that class, so the
    # result is one connected graph rather than a row of disjoint pairs.
    named = {}
    labels = {}

    def individual(cls, nth=1):
        """The nth individual of a class, minted on demand.

        A SECOND ONE IS NEEDED WHEN A PROPERTY RELATES A CLASS TO ITSELF. hasComponent in eep
        and affordance has the same class as its domain and its range, and reusing one
        individual made the example assert `Entity1 hasComponent Entity1` - a self-loop on a
        property the pattern declares ASYMMETRIC, so the example contradicted the pattern. Two
        individuals is what the relation is actually about.
        """
        key = (cls, nth)
        if key not in named:
            name = "ex:" + safe_name(local(cls)) + str(nth)
            named[key] = name
            said = shape["labels"].get(cls)
            if said:
                article = "an" if said[:1].upper() in "AEIOU" else "a"
                labels[name] = article + " " + said + ("" if nth == 1 else " (another)")
        return named[key]

    prefixes = {
        "ex": "https://w3id.org/ontoboard/example/" + pattern_id + "#",
        "owl": "http://www.w3.org/2002/07/owl#",
        "rdfs": "http://www.w3.org/2000/01/rdf-schema#",
        "xsd": "http://www.w3.org/2001/XMLSchema#",
    }
    used = {}
    for cls in shape["classes"]:
        iri = str(cls)
        cut = max(iri.rfind("#"), iri.rfind("/"))
        base = iri[:cut + 1]
        if base in used.values():
            continue
        # A readable prefix, in order of preference: one the pattern declares, then one made
        # from the namespace itself. Most of these patterns bind their own namespace to the
        # DEFAULT prefix - `@prefix : <...agentrole.owl#>` - which cannot be reused here, so
        # without the second rule every example would be full of ns0: and say nothing.
        short = None
        for prefix, namespace in shape["namespaces"].items():
            if str(namespace) == base and prefix and prefix not in prefixes:
                short = prefix
                break
        if not short:
            stem = base.rstrip("#/").rsplit("/", 1)[-1]
            stem = re.sub(r"\.(owl|ttl|rdf)$", "", stem)
            stem = re.sub(r"[^A-Za-z0-9]+", "", stem).lower()
            if stem and stem not in prefixes and stem not in used:
                short = stem
        used[short or ("ns%d" % len(used))] = base

    lines = []
    lines.append(GENERATED)
    lines.append("# names, and delete this line and the next so that --force is needed to lose")
    lines.append("# your work. The structure below is read from the pattern's own rdfs:domain")
    lines.append("# and rdfs:range, so the direction of every property is the pattern's.")
    lines.append("")
    for prefix, namespace in sorted(used.items()):
        lines.append("@prefix %s: <%s> ." % (prefix, namespace))
    wanted = ["ex", "owl", "rdfs"]
    if any(literal_for(one["range"]).endswith("^^xsd:date")
           or "^^xsd:" in literal_for(one["range"]) for one in shape["data"]):
        wanted.append("xsd")
    for prefix in wanted:
        lines.append("@prefix %s: <%s> ." % (prefix, prefixes[prefix]))
    lines.append("")

    def curie(iri):
        """A prefixed name where Turtle allows one, and the full IRI where it does not.

        The food-recipe patterns have classes called `food_recipe_ingredient_substitution_
        (specification)`. Parentheses are not legal in a Turtle prefixed name, so writing that
        after a prefix produces a file that does not parse - which is what the first version of
        this did, twice, and the checker caught.
        """
        said = str(iri)
        for prefix, namespace in sorted(used.items()):
            if said.startswith(namespace):
                rest = said[len(namespace):]
                if rest and re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_-]*", rest):
                    return prefix + ":" + rest
                break
        return "<" + said + ">"

    statements = {}
    # ONLY THE CLASSES AN EDGE TOUCHES. The first version minted one individual per declared
    # class, so every class that no property mentions became an individual sitting on its own -
    # 22 of them in actuation-actuator-effect, and 119 of the 162 examples had at least one. A
    # pile of unconnected individuals does not show a shape; it shows a list. When the pattern
    # has no properties at all there is nothing to connect, and then the leaf classes are the
    # example.
    if not links:
        for cls in shape["leaves"]:
            statements.setdefault(individual(cls), {"types": set(), "out": []})
            statements[individual(cls)]["types"].add(curie(cls))
    for link in links:
        # The second individual only where the two ends are the same class.
        ends = [(link["domain"], 1),
                (link["range"], 2 if link["range"] == link["domain"] else 1)]
        extra = {ends[0][0]: link.get("domains") or [], ends[1][0]: link.get("ranges") or []}
        for cls, nth in ends:
            statements.setdefault(individual(cls, nth), {"types": set(), "out": []})
            # Every domain axiom, not just the first: OWL reads several as a conjunction.
            for also in extra.get(cls) or [cls]:
                if also in shape["classes"]:
                    statements[individual(cls, nth)]["types"].add(curie(also))
        statements[individual(*ends[0])]["out"].append(
            (curie(link["property"]), individual(*ends[1])))
    for one in shape["data"]:
        # A property whose domain the pattern does not declare is a defect IN THE PATTERN, and
        # instantiating it would put an untyped individual in the example and hide the defect.
        # bag:size has domain Collection, and bag declares only Bag and Item.
        if not one["domain"] or one["domain"] not in shape["classes"]:
            continue
        statements.setdefault(individual(one["domain"]), {"types": set(), "out": []})
        statements[individual(one["domain"])]["out"].append(
            (curie(one["property"]), literal_for(one["range"])))

    # PRUNE ANYTHING WITH NO OBJECT EDGE. An individual whose only edge is a literal - bag's
    # Collection, which is imported and carries nothing but `size` - is invisible at level of
    # detail 3, where literals are hidden, so it draws as a lone dot and teaches nothing. It is
    # kept only when the example has no object edges at all, which is the thin-pattern case.
    linked = set()
    for subject, held in statements.items():
        for prop, obj in held["out"]:
            if obj.startswith("ex:"):
                linked.add(subject)
                linked.add(obj)
    if linked:
        statements = {name: held for name, held in statements.items() if name in linked}

    for subject in sorted(statements):
        held = statements[subject]
        types = ["owl:NamedIndividual"] + sorted(held["types"])
        label = labels.get(subject) or readable(subject[3:-1])
        lines.append(subject + " a " + " , ".join(types) + " ;")
        lines.append('    rdfs:label "' + label + '"' + (" ;" if held["out"] else " ."))
        for at, (prop, obj) in enumerate(sorted(held["out"])):
            last = at == len(held["out"]) - 1
            lines.append("    " + prop + " " + obj + (" ." if last else " ;"))
        lines.append("")

    inverse_note = [l for l in shape["links"] if l["inverse"]]
    if inverse_note:
        lines.append("# Only one direction of each inverse pair is asserted: "
                     + ", ".join(sorted(local(l["property"]) + "/" + local(l["inverse"])
                                        for l in inverse_note))
                     + ". A reasoner adds the other.")
        lines.append("")

    return "\n".join(lines), None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true",
                        help="rewrite an example even if a curator has edited it")
    parser.add_argument("--only", help="one pattern id")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 if any pattern has no example")
    args = parser.parse_args()

    try:
        import rdflib  # noqa: F401
    except ImportError:
        print("this needs rdflib: python -m pip install rdflib", file=sys.stderr)
        return 2

    ids = sorted(d for d in os.listdir(PATTERNS)
                 if os.path.isdir(os.path.join(PATTERNS, d)))
    if args.only:
        ids = [i for i in ids if i == args.only]
        if not ids:
            print("no pattern called " + args.only, file=sys.stderr)
            return 2

    library = local_library()
    wrote, kept, curated, refused, broken = 0, 0, 0, [], []
    for pattern_id in ids:
        folder = os.path.join(PATTERNS, pattern_id)
        source = os.path.join(folder, "pattern.ttl")
        target = os.path.join(folder, "example.ttl")
        if not os.path.isfile(source):
            refused.append((pattern_id, "it has no pattern.ttl"))
            continue
        if os.path.isfile(target) and not args.force:
            held = io.open(target, encoding="utf-8").read()
            if GENERATED in held:
                kept += 1
            else:
                curated += 1
                continue
        try:
            shape = shape_of(source, library)
        except Exception as cannotRead:          # noqa: BLE001 - the reason is what matters
            broken.append((pattern_id, type(cannotRead).__name__ + ": " + str(cannotRead)[:90]))
            continue
        text, why = example_for(pattern_id, shape)
        if text is None:
            refused.append((pattern_id, why))
            continue
        if args.check:
            continue
        io.open(target, "w", encoding="utf-8", newline="\n").write(text + "\n")
        wrote += 1

    print("patterns:            %d" % len(ids))
    print("examples written:    %d" % wrote)
    print("left alone, curated: %d" % curated)
    print("refused:             %d" % len(refused))
    for pattern_id, why in refused:
        print("    %-34s %s" % (pattern_id, why))
    if broken:
        print("could not read:      %d" % len(broken))
        for pattern_id, why in broken:
            print("    %-34s %s" % (pattern_id, why))

    if args.check:
        missing = [i for i in ids
                   if not os.path.isfile(os.path.join(PATTERNS, i, "example.ttl"))]
        if missing:
            print("%d pattern(s) have no example.ttl" % len(missing), file=sys.stderr)
            return 1
    return 1 if broken else 0


if __name__ == "__main__":
    sys.exit(main())
